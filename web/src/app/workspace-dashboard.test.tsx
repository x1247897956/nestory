import {render,screen,fireEvent} from '@testing-library/react';
import {expect,it,vi} from 'vitest';
import {createMemoryRouter,RouterProvider} from 'react-router-dom';
import {QueryClient,QueryClientProvider} from '@tanstack/react-query';
import {Workspace} from '../features/workspace/Workspace';
vi.mock('@fullcalendar/react',()=>({default:()=> <div>日历组件</div>}));
it('shows all open work and filters overdue tasks without timezone or creation controls',()=>{
 const client=new QueryClient({defaultOptions:{queries:{retry:false,staleTime:Infinity}}});
 const item={id:'t',type:'tasks',title:'修复阻塞',project_id:'p',project_title:'Noteapp',due_date:'2026-10-23',archived:false};
 client.setQueryData(['recent'],[]);
 client.setQueryData(['config'],{timezone:'Asia/Shanghai'});
 client.setQueryData(['workspace',undefined],{date:'2026-10-24',timezone:'Asia/Shanghai',tasks:[item,{...item,id:'future',title:'未来行动',due_date:'2026-11-20'},{...item,id:'undated',title:'未定日期',due_date:undefined}],events:[]});
 const router=createMemoryRouter([{path:'/',element:<Workspace/>}]);
 render(<QueryClientProvider client={client}><RouterProvider router={router}/></QueryClientProvider>);
 expect(screen.queryByText(/Asia\/Shanghai/)).not.toBeInTheDocument();
 expect(screen.queryByRole('button',{name:/创建.*项目/})).not.toBeInTheDocument();
 expect(screen.getByRole('region',{name:'日程日历'})).toBeVisible();
 expect(screen.getByRole('link',{name:/未来行动/})).toBeVisible();
 expect(screen.getByRole('link',{name:/未定日期/})).toBeVisible();
 fireEvent.click(screen.getByRole('button',{name:'逾期'}));
 expect(screen.queryByRole('link',{name:/未来行动/})).not.toBeInTheDocument();
 expect(screen.getByRole('link',{name:/修复阻塞/})).toBeVisible();
});
