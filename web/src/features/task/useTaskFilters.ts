import {DateTime} from 'luxon';
import {useMemo,useState,useEffect} from 'react';
import {useQuery} from '@tanstack/react-query';
import {api} from '../../app/api';
import {filterFields,matchesFilters,readFilters,validFilters,type TaskFilter,type PropertySnapshot,type FilterObject} from './filterEngine';
const storageKey=(id:string,type:'tasks'|'pages')=>`noteapp:${type==='tasks'?'task':'page'}-filters:v1:${id}`;
export function useTaskFilters(projectId:string|undefined,tasks:FilterObject[],enabled:boolean,type:'tasks'|'pages'='tasks'){
 const [choices,setChoices]=useState<Record<string,TaskFilter[]>>({});
 const [preferenceEpoch,setPreferenceEpoch]=useState(0);
 useEffect(()=>{const reset=()=>{setChoices({});setPreferenceEpoch(value=>value+1);};window.addEventListener('noteapp:preferences-reset',reset);return()=>window.removeEventListener('noteapp:preferences-reset',reset);},[]);
 const id=projectId??'';
 const key=`${type}:${id}`;
 const saved=useMemo(()=>{try{return readFilters(localStorage.getItem(storageKey(id,type)));}catch{return [];}},[key,preferenceEpoch]);
 const filters=choices[key]??saved;
 const setFilters=(next:TaskFilter[])=>{setChoices(old=>({...old,[key]:next}));try{if(id)localStorage.setItem(storageKey(id,type),JSON.stringify(next));}catch{/* Session-only preferences remain usable. */}};
 const properties=useQuery({queryKey:['object',type==='tasks'?'task-filter-properties':'page-filter-properties',projectId],queryFn:()=>api<PropertySnapshot>(`/projects/${projectId}/property-snapshot/${type}`),enabled:!!projectId&&enabled});
 const config=useQuery({queryKey:['config'],queryFn:()=>api<{timezone:string}>('/config'),enabled:enabled});
 const [clock,setClock]=useState(Date.now());
 useEffect(()=>{if(enabled)setClock(Date.now());},[enabled]);
 useEffect(()=>{
  if(!enabled)return;
  const zone=config.data?.timezone??'UTC';
  const tick=()=>setClock(Date.now());
  const next=DateTime.now().setZone(zone).plus({days:1}).startOf('day').toMillis();
  const timer=window.setTimeout(tick,Math.max(50,next-Date.now()+50));
  window.addEventListener('focus',tick);
  return ()=>{clearTimeout(timer);window.removeEventListener('focus',tick);};
 },[enabled,config.data?.timezone,clock]);
 const fields=useMemo(()=>filterFields(properties.data?.definitions??[],type),[properties.data,type]);
 const builtin=filterFields([],type);
 const custom=filters.some(f=>!builtin.some(field=>field.id===f.field));
 const relative=filters.some(f=>['today','week'].includes(f.op));
 const needsZone=relative||(type==='pages'&&filters.some(f=>['created_at','updated_at'].includes(f.field)));
 const pending=(custom&&properties.isPending)||(needsZone&&config.isPending);
 const failed=(custom&&properties.isError)||(needsZone&&config.isError);
 const invalid=!pending&&!failed&&!validFilters(filters,fields);
 const blocked=pending||failed||invalid;
 const ids=useMemo(()=>new Set(blocked?[]:tasks.filter(t=>matchesFilters(t,filters,properties.data?.values??{},config.data?.timezone??'UTC',new Date(clock).toISOString())).map(t=>t.id)),[tasks,filters,properties.data,config.data,blocked,clock]);
 return {filters,setFilters,fields,ids,blocked,pending,failed,invalid,properties,config};
}
export type TaskFilterState=ReturnType<typeof useTaskFilters>;
